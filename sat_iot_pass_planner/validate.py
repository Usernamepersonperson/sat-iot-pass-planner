"""Validation of the propagation chain against published references.

* SGP4: the Vallado/Hoots/Seago/Kelso verification set (AIAA 2006-6753, "Revisiting Spacetrack Report #3"): element sets
  and reference TEME states generated by the reference C++ implementation. The files ship inside the ``sgp4`` package
  (``SGP4-VER.TLE`` and ``tcppver.out``); we read them from there instead of copying them.
* Sidereal time: Vallado, "Fundamentals of Astrodynamics and Applications", Example 3-5 (1992-08-20 12:14 UT1).
"""

from __future__ import annotations

import re
from pathlib import Path

import numpy as np
import sgp4
from sgp4.api import WGS72, Satrec

from .propagate import gmst_rad, propagate_teme
from .tle import Tle

GMST_EXAMPLE = {"jd": 2448855.009722222, "gmst_deg": 152.578787810}


def _pkg_file(name: str) -> Path:
    return Path(sgp4.__file__).parent / name


def read_reference_elements() -> list[tuple[Tle, float, float, float]]:
    """(element set, start min, stop min, step min) for each case in the verification TLE file."""
    out = []
    lines = [ln.rstrip("\n") for ln in _pkg_file("SGP4-VER.TLE").read_text().splitlines()]
    i = 0
    while i < len(lines) - 1:
        if lines[i].startswith("1 ") and lines[i + 1].startswith("2 "):
            l1, l2 = lines[i][:69], lines[i + 1][:69]
            extra = lines[i + 1][69:].split()
            out.append((Tle(int(l1[2:7]), l1, l2), float(extra[0]), float(extra[1]), float(extra[2])))
            i += 2
        else:
            i += 1
    return out


def read_reference_states() -> dict[int, list[tuple[float, np.ndarray, np.ndarray]]]:
    """norad -> [(tsince_min, r_km, v_km_s)] from the reference output file."""
    states: dict[int, list] = {}
    cur = None
    for ln in _pkg_file("tcppver.out").read_text().splitlines():
        m = re.match(r"^\s*(\d+)\s+xx", ln)
        if m:
            cur = int(m.group(1))
            states[cur] = []
            continue
        tok = ln.split()
        if cur is None or len(tok) < 7:
            continue
        try:
            vals = [float(x) for x in tok[:7]]
        except ValueError:
            continue
        states[cur].append((vals[0], np.array(vals[1:4]), np.array(vals[4:7])))
    return states


def sgp4_against_reference() -> dict:
    """Propagate every reference case with this project's propagation path and compare positions with the published values."""
    states = read_reference_states()
    max_err = 0.0
    rows = 0
    worst = None
    cases = 0
    for tle, _t0, _t1, _dt in read_reference_elements():
        ref = states.get(tle.norad)
        if not ref:
            continue
        sat = Satrec.twoline2rv(tle.line1, tle.line2, WGS72)
        cases += 1
        for tsince, r_ref, _v in ref:
            fr_total = sat.jdsatepochF + tsince / 1440.0
            jd = np.array([sat.jdsatepoch + np.floor(fr_total)])
            fr = np.array([fr_total - np.floor(fr_total)])
            r, ok = propagate_teme([tle], jd, fr)
            if not ok[0, 0]:
                continue  # reference run also stopped at SGP4 error states
            err = float(np.linalg.norm(r[0, 0] - r_ref))
            rows += 1
            if err > max_err:
                max_err, worst = err, (tle.norad, tsince)
    return {"cases": cases, "states_compared": rows, "max_position_error_km": max_err, "worst_case": worst}


def gmst_example() -> dict:
    g = float(np.degrees(gmst_rad(np.array([GMST_EXAMPLE["jd"]]), np.array([0.0])))[0])
    return {"computed_deg": g, "published_deg": GMST_EXAMPLE["gmst_deg"], "error_deg": abs(g - GMST_EXAMPLE["gmst_deg"])}


def run_validation(tol_km: float = 1e-5, tol_gmst_deg: float = 1e-5) -> dict:
    sg = sgp4_against_reference()
    gm = gmst_example()
    return {
        "sgp4": sg,
        "gmst": gm,
        "tolerance_km": tol_km,
        "passed": bool(sg["states_compared"] > 100 and sg["max_position_error_km"] <= tol_km and gm["error_deg"] <= tol_gmst_deg),
    }
